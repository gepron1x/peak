-- Схема БД приложения «АльпКлуб»

create table mountain (
    id      bigint generated by default as identity primary key,
    name    varchar(150) not null,
    height  integer      not null check (height > 0),
    country varchar(100) not null,
    region  varchar(100) not null
);

-- Повтор горы с совпадением названия, страны и района без учета регистра запрещен
create unique index uq_mountain_name_country_region
    on mountain (lower(name), lower(country), lower(region));

create table climber (
    id      bigint generated by default as identity primary key,
    name    varchar(200) not null,
    address varchar(300) not null
);

create table ascent (
    id         bigint generated by default as identity primary key,
    group_name varchar(150) not null,
    mountain_id bigint      not null references mountain (id),
    start_time timestamp    not null,
    end_time   timestamp,
    constraint chk_ascent_end_not_before_start
        check (end_time is null or end_time >= start_time)
);

create index idx_ascent_start_time on ascent (start_time);
create index idx_ascent_mountain on ascent (mountain_id);

create table participation (
    ascent_id  bigint not null references ascent (id) on delete cascade,
    climber_id bigint not null references climber (id),
    primary key (ascent_id, climber_id)
);

create index idx_participation_climber on participation (climber_id);
